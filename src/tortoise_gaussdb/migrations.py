"""Tortoise native migration operations with a GaussDB executor/recorder.

1.1.8 has no third-party schema-editor registration hook. Use this explicit
entry point instead of patching the upstream process globally.
"""

from __future__ import annotations

import argparse
import asyncio
import importlib

from tortoise import Tortoise
from tortoise.migrations.executor import MigrationExecutor, MigrationTarget
from tortoise.migrations.graph import MigrationKey
from tortoise.migrations.recorder import MigrationRecorder
from tortoise.migrations.schema_editor.base_postgres import BasePostgresSchemaEditor
from tortoise.migrations.schema_editor.data import ModelSqlData
from tortoise.transactions import in_transaction

from tortoise_gaussdb.schema import (
    DistributionMixin,
    GaussDBSchemaGenerator,
    create_schema_sql,
    quote_identifier,
)


class GaussDBSchemaEditor(DistributionMixin, BasePostgresSchemaEditor):
    async def add_field(self, model, field_name):
        from tortoise.fields.relational import (
            ForeignKeyFieldInstance,
            ManyToManyFieldInstance,
        )

        field = model._meta.fields_map[field_name]
        self._model_distribution(model)
        if isinstance(field, ManyToManyFieldInstance):
            if field._generated:
                return
            generator = GaussDBSchemaGenerator(self.client)
            generator._active_model = model
            excluded = [
                model._meta.fields_map[name].through
                for name in model._meta.m2m_fields
                if model._meta.fields_map[name].through != field.through
            ]
            # Share the proven schema path: upstream's migration template
            # ignores db_constraint=False and has no distribution layout.
            statements = generator._get_m2m_tables(
                model, model._meta.db_table, False, excluded
            )
            if len(statements) != 1:
                raise ValueError("M2M migration requires one explicit through table")
            await self._run_sql(statements[0])
            return
        if isinstance(field, ForeignKeyFieldInstance) and not field.db_constraint:
            # Upstream's FK migration path unconditionally adds REFERENCES,
            # even for logical relations. Add the initialized backing field
            # through the ordinary column path to preserve its type/defaults.
            field_name = field.source_field or field_name + "_id"
        await super().add_field(model, field_name)
        comments = self._post_table_hook()
        if comments:
            await self._run_sql(comments)

    async def create_schema(self, schema_name):
        await self._run_sql(create_schema_sql(schema_name))

    async def drop_schema(self, schema_name):
        # The connection schema owns migration history and may predate this
        # app. Reversing an autogenerated CreateSchema must not CASCADE it.
        if schema_name == (self.client.schema or "public"):
            if self.collect_sql:
                self.collected_sql.append(
                    "-- Preserve connection schema and migration history"
                )
            return
        await self._run_sql(
            f"DROP SCHEMA IF EXISTS {self.quote(schema_name)} RESTRICT;"
        )

    def _get_model_sql_data(self, model):
        generator = GaussDBSchemaGenerator(self.client)
        generator._get_models_to_create = lambda: [model]
        data = generator._get_table_sql(model, safe=False)
        return ModelSqlData(
            data["table"],
            model,
            data["table_creation_string"],
            data["references"],
            data["m2m_tables"],
        )

    async def rename_table(self, model, old_name, new_name):
        if old_name != new_name:
            await self._run_sql(
                f"ALTER TABLE {self._qualify_table_name(old_name, model._meta.schema)} "
                f"RENAME TO {self.quote(new_name)};"
            )

    async def remove_index(self, model, index):
        name = self._index_name_for_model(model, index)
        await self._run_sql(
            f"DROP INDEX {self._qualify_table_name(name, model._meta.schema)};"
        )

    async def rename_index(self, model, old_index, new_index):
        old_name = self._index_name_for_model(model, old_index)
        new_name = self._index_name_for_model(model, new_index)
        if old_name != new_name:
            await self._run_sql(
                f"ALTER INDEX {self._qualify_table_name(old_name, model._meta.schema)} "
                f"RENAME TO {self.quote(new_name)};"
            )

    async def remove_constraint(self, model, constraint):
        from tortoise.migrations.constraints import UniqueConstraint

        if isinstance(constraint, UniqueConstraint) and constraint.condition:
            fields = self._resolve_fields_to_columns(model, constraint.fields)
            resolved = UniqueConstraint(
                fields=tuple(fields), name=constraint.name, condition=constraint.condition
            )
            name = self._constraint_name_for_model(model, resolved)
            await self._run_sql(
                f"DROP INDEX {self._qualify_table_name(name, model._meta.schema)};"
            )
            return
        await super().remove_constraint(model, constraint)

    async def _get_unique_constraint_names_from_db(
        self, table_name, column_names, schema=None
    ):
        # Do not interpolate identifiers as string literals into upstream SQL.
        _, rows = await self.client.execute_query(
            "SELECT con.conname, att.attname, att.attnum, con.conkey "
            "FROM pg_constraint con JOIN pg_class rel ON rel.oid=con.conrelid "
            "JOIN pg_namespace nsp ON nsp.oid=rel.relnamespace "
            "JOIN pg_attribute att ON att.attrelid=rel.oid AND att.attnum=ANY(con.conkey) "
            "WHERE rel.relname=%s AND nsp.nspname=%s AND con.contype='u'",
            [table_name, schema or "public"],
        )
        groups = {}
        for row in rows:
            groups.setdefault(row["conname"], set()).add(row["attname"])
        return [
            name for name, columns in groups.items() if columns == set(column_names)
        ]


class GaussDBMigrationRecorder(MigrationRecorder):
    def __init__(self, connection):
        super().__init__(connection)
        self.model._meta.schema = connection.schema or "public"

    def _placeholder(self, pos):
        return "%s"

    def _quote(self, name):
        if name == self.table_name:
            return (
                quote_identifier(self.model._meta.schema) + "." + quote_identifier(name)
            )
        return quote_identifier(name)

    async def ensure_schema(self, schema_editor):
        await schema_editor.create_schema(self.model._meta.schema)
        await super().ensure_schema(schema_editor)

    async def applied_migrations(self):
        # Only a genuinely absent history table means "no migrations".
        # Permission, connection, and syntax failures must propagate.
        _, found = await self.connection.execute_query(
            "SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace "
            "WHERE n.nspname=%s AND c.relname=%s",
            [self.model._meta.schema, self.table_name],
        )
        if not found:
            return []
        _, rows = await self.connection.execute_query(
            f"SELECT app, name FROM {self._quote(self.table_name)} ORDER BY applied_at, app, name"
        )
        return [MigrationKey(app_label=row["app"], name=row["name"]) for row in rows]


class GaussDBMigrationExecutor(MigrationExecutor):
    def __init__(self, connection, apps_config):
        super().__init__(connection, apps_config)
        self.recorder = GaussDBMigrationRecorder(connection)
        self.loader.recorder = self.recorder
        # Internal history uses an explicit replicated layout. It has two
        # independent unique keys (id and app/name), unsuitable for HASH(id).
        key = f"{connection.schema or 'public'}.tortoise_migrations"
        if connection.deployment == "distributed":
            connection.distributions.setdefault(key, {"type": "REPLICATION"})

    def _schema_editor(self, atomic=True, collect_sql=False):
        return GaussDBSchemaEditor(self.connection, atomic, collect_sql)

    async def collect_sql(self, app_label, migration_name, *, backward=False):
        class OfflineHistory:
            async def applied_migrations(self):
                return []

        recorder = self.loader.recorder
        self.loader.recorder = OfflineHistory()
        try:
            return await super().collect_sql(
                app_label, migration_name, backward=backward
            )
        finally:
            self.loader.recorder = recorder

    async def migrate(
        self,
        targets=None,
        *,
        fake=False,
        dry_run=False,
        direction="both",
        progress=None,
    ):
        if dry_run:
            # Upstream migrate(dry_run=True) creates a history table; use plan
            # instead, so preview does not create database objects.
            return await self.plan(targets)
        if fake:
            raise ValueError("Fake migrations are not supported by this adapter")
        self.loader.load_disk()
        for migration in self.loader.disk_migrations.values():
            if not migration.atomic:
                raise ValueError(
                    "Non-atomic migrations are not supported by this executor"
                )
        await self.recorder.ensure_schema(self._schema_editor(atomic=False))
        original = self.connection
        try:
            async with in_transaction(original.connection_name) as tx:
                self.connection = tx
                self.recorder.connection = tx
                await tx.execute_script(
                    f"LOCK TABLE {self.recorder._quote(self.recorder.table_name)} IN EXCLUSIVE MODE"
                )
                # DDL and history updates commit together. A failed batch rolls
                # back all pending migrations in this invocation.
                return await super().migrate(
                    targets, direction=direction, progress=progress
                )
        finally:
            self.connection = original
            self.recorder.connection = original


async def run(config, command="migrate", app=None, name=None, backward=False):
    await Tortoise.init(config=config, init_connections=False)
    try:
        grouped = {}
        for label, settings in config["apps"].items():
            grouped.setdefault(settings.get("default_connection", "default"), {})[
                label
            ] = settings
        output = []
        for alias, apps in grouped.items():
            if app and app not in apps:
                continue
            executor = GaussDBMigrationExecutor(Tortoise.get_connection(alias), apps)
            if command == "sqlmigrate":
                if not app or not name:
                    raise ValueError("sqlmigrate requires --app and --name")
                output.extend(await executor.collect_sql(app, name, backward=backward))
            else:
                targets = [MigrationTarget(app, name or "__latest__")] if app else None
                if command == "plan":
                    output.extend(str(step) for step in await executor.plan(targets))
                else:
                    await executor.migrate(targets)
        if app and app not in config["apps"]:
            raise ValueError(f"Unknown app {app}")
        return output
    finally:
        await Tortoise.close_connections()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["migrate", "plan", "sqlmigrate"])
    parser.add_argument("-c", "--config", required=True, help="module:CONFIG")
    parser.add_argument("--app")
    parser.add_argument("--name", help="Migration name or __first__ to roll back all")
    parser.add_argument("--backward", action="store_true", help="Preview reverse SQL")
    args = parser.parse_args()
    module, attr = args.config.split(":", 1)
    config = getattr(importlib.import_module(module), attr)
    for line in asyncio.run(
        run(config, args.command, args.app, args.name, args.backward)
    ):
        print(line)


if __name__ == "__main__":
    main()
